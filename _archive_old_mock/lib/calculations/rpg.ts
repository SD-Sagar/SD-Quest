import { AttributeType, HunterRank } from "@/types";

/**
 * Calculates XP required to advance from currentLevel to currentLevel + 1.
 * Uses a power-curve formula calibrated for lifelong progression (decades without capping).
 */
export function calculateXpForNextLevel(level: number): number {
  if (level <= 1) return 100;
  return Math.floor(100 * Math.pow(level, 1.55));
}

/**
 * Determines Hunter Rank tier based on current player level.
 */
export function getRankForLevel(level: number): HunterRank {
  if (level >= 60) return "Spartan";
  if (level >= 35) return "Vanguard";
  if (level >= 15) return "Warrior";
  return "Recruit";
}

/**
 * Difficulty Multipliers for XP & Stat Yields
 */
export const DIFFICULTY_MULTIPLIERS: Record<HunterRank, number> = {
  Recruit: 1.0,
  Warrior: 1.25,
  Vanguard: 1.6,
  Spartan: 2.0,
};

/**
 * Calculates fair XP reward for a quest based on duration, priority, and difficulty
 */
export function calculateFairQuestXp(
  durationMinutes: number,
  difficulty: HunterRank,
  priority: "low" | "medium" | "high" | "urgent"
): number {
  const baseMinutes = Math.max(5, durationMinutes);
  const priorityMultiplier =
    priority === "urgent" ? 1.5 : priority === "high" ? 1.25 : priority === "medium" ? 1.0 : 0.8;
  const diffMultiplier = DIFFICULTY_MULTIPLIERS[difficulty];

  // ~1 XP per minute of focused effort at Recruit tier, scaled by difficulty and priority
  const rawXp = (baseMinutes * 1.0) * priorityMultiplier * diffMultiplier;
  return Math.round(rawXp);
}

/**
 * Fair Stat Allocation Calculator for Manual & Smart Quests.
 * Ensures points awarded reflect realistic physical and cognitive volume without exploits.
 */
export function calculateFairStatYield(
  durationMinutes: number,
  difficulty: HunterRank,
  selectedAttributes: AttributeType[]
): Record<AttributeType, number> {
  const result: Partial<Record<AttributeType, number>> = {};
  if (selectedAttributes.length === 0) return result as Record<AttributeType, number>;

  const hours = Math.max(0.1, durationMinutes / 60);
  const diffMult = DIFFICULTY_MULTIPLIERS[difficulty];

  // Base pool of attribute points generated by this session
  const totalPool = Number((hours * 0.4 * diffMult).toFixed(2));
  const sharePerStat = Number((totalPool / selectedAttributes.length).toFixed(2));

  for (const attr of selectedAttributes) {
    result[attr] = Math.max(0.05, sharePerStat);
  }

  return result as Record<AttributeType, number>;
}

